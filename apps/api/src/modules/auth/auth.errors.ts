import { HttpStatus } from '@nestjs/common';

import { DomainException } from '../../common/exceptions/index.js';

export const AUTH_ERRORS = {
  INVALID_CREDENTIALS: 'INVALID_CREDENTIALS',
  TOO_MANY_LOGIN_ATTEMPTS: 'TOO_MANY_LOGIN_ATTEMPTS',
  INVALID_CODE: 'INVALID_CODE',
  CODE_RESEND_TOO_SOON: 'CODE_RESEND_TOO_SOON',
  INVALID_REFRESH_TOKEN: 'INVALID_REFRESH_TOKEN',
  REFRESH_TOKEN_REUSED: 'REFRESH_TOKEN_REUSED',
  REFRESH_IN_PROGRESS: 'REFRESH_IN_PROGRESS',
  OIDC_PROVIDER_DISABLED: 'OIDC_PROVIDER_DISABLED',
  INVALID_ID_TOKEN: 'INVALID_ID_TOKEN',
  OIDC_EMAIL_REQUIRED: 'OIDC_EMAIL_REQUIRED',
  CURRENT_PASSWORD_INVALID: 'CURRENT_PASSWORD_INVALID',
  SESSION_NOT_FOUND: 'SESSION_NOT_FOUND',
} as const;

type AuthErrorCode = (typeof AUTH_ERRORS)[keyof typeof AUTH_ERRORS];

const STATUS: Record<AuthErrorCode, HttpStatus> = {
  INVALID_CREDENTIALS: HttpStatus.UNAUTHORIZED,
  TOO_MANY_LOGIN_ATTEMPTS: HttpStatus.TOO_MANY_REQUESTS,
  INVALID_CODE: HttpStatus.BAD_REQUEST,
  CODE_RESEND_TOO_SOON: HttpStatus.TOO_MANY_REQUESTS,
  INVALID_REFRESH_TOKEN: HttpStatus.UNAUTHORIZED,
  REFRESH_TOKEN_REUSED: HttpStatus.UNAUTHORIZED,
  REFRESH_IN_PROGRESS: HttpStatus.CONFLICT,
  OIDC_PROVIDER_DISABLED: HttpStatus.NOT_FOUND,
  INVALID_ID_TOKEN: HttpStatus.UNAUTHORIZED,
  OIDC_EMAIL_REQUIRED: HttpStatus.BAD_REQUEST,
  CURRENT_PASSWORD_INVALID: HttpStatus.FORBIDDEN,
  SESSION_NOT_FOUND: HttpStatus.NOT_FOUND,
};

export class AuthException extends DomainException {
  constructor(code: AuthErrorCode) {
    super(code, STATUS[code]);
  }
}
