import { HttpStatus } from '@nestjs/common';

import { DomainException, type DomainExceptionOptions } from '../../common/exceptions/index.js';

export const KNOWLEDGE_ERRORS = {
  NODE_NOT_FOUND: 'KNOWLEDGE_NOT_FOUND',
  NODE_NOT_PUBLISHED: 'KNOWLEDGE_NOT_PUBLISHED',
  NODE_CYCLE: 'KNOWLEDGE_CYCLE',
  NODE_PARENT_INVALID: 'KNOWLEDGE_PARENT_INVALID',
  NODE_TITLE_TAKEN: 'KNOWLEDGE_TITLE_TAKEN',
  NODE_BODY_REQUIRED: 'KNOWLEDGE_BODY_REQUIRED',
  SOURCE_FAILED: 'KNOWLEDGE_SOURCE_FAILED',
  SOURCE_TOO_LARGE: 'KNOWLEDGE_SOURCE_TOO_LARGE',
  SOURCE_FORMAT_UNSUPPORTED: 'KNOWLEDGE_SOURCE_FORMAT_UNSUPPORTED',
  SOURCE_NOT_FOUND: 'KNOWLEDGE_SOURCE_NOT_FOUND',
  PROPOSAL_NOT_FOUND: 'KNOWLEDGE_PROPOSAL_NOT_FOUND',
  PROPOSAL_CLOSED: 'KNOWLEDGE_PROPOSAL_CLOSED',
  FORBIDDEN: 'KNOWLEDGE_FORBIDDEN',
} as const;

export type KnowledgeErrorCode = (typeof KNOWLEDGE_ERRORS)[keyof typeof KNOWLEDGE_ERRORS];

const STATUS: Record<KnowledgeErrorCode, HttpStatus> = {
  KNOWLEDGE_NOT_FOUND: HttpStatus.NOT_FOUND,
  KNOWLEDGE_NOT_PUBLISHED: HttpStatus.NOT_FOUND,
  KNOWLEDGE_CYCLE: HttpStatus.BAD_REQUEST,
  KNOWLEDGE_PARENT_INVALID: HttpStatus.BAD_REQUEST,
  KNOWLEDGE_TITLE_TAKEN: HttpStatus.CONFLICT,
  KNOWLEDGE_BODY_REQUIRED: HttpStatus.BAD_REQUEST,
  KNOWLEDGE_SOURCE_FAILED: HttpStatus.UNPROCESSABLE_ENTITY,
  KNOWLEDGE_SOURCE_TOO_LARGE: HttpStatus.PAYLOAD_TOO_LARGE,
  KNOWLEDGE_SOURCE_FORMAT_UNSUPPORTED: HttpStatus.UNSUPPORTED_MEDIA_TYPE,
  KNOWLEDGE_SOURCE_NOT_FOUND: HttpStatus.NOT_FOUND,
  KNOWLEDGE_PROPOSAL_NOT_FOUND: HttpStatus.NOT_FOUND,
  KNOWLEDGE_PROPOSAL_CLOSED: HttpStatus.CONFLICT,
  KNOWLEDGE_FORBIDDEN: HttpStatus.FORBIDDEN,
};

export class KnowledgeException extends DomainException {
  constructor(code: KnowledgeErrorCode, options?: DomainExceptionOptions) {
    super(code, STATUS[code], options);
  }
}
