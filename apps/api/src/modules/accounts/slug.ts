import { randomBytes } from 'node:crypto';

const TRANSLIT: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
};

export const SLUG_PATTERN = /^[a-z0-9][a-z0-9-]{1,62}$/;

/** URL-safe slug from a display name (Cyrillic transliterated); random fallback. */
export function slugify(name: string, fallbackPrefix = 'account'): string {
  const base = [...name.toLowerCase()]
    .map((char) => TRANSLIT[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48);
  return SLUG_PATTERN.test(base) ? base : `${fallbackPrefix}-${randomSuffix()}`;
}

export function randomSuffix(): string {
  return randomBytes(3).toString('hex');
}
